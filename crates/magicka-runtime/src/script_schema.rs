//! Native trigger Action/Condition class schema and a host-language call
//! surface over it.
//!
//! **PROVEN (decompiled Action.Read / Condition.Read):** a scene XML element
//! names a class by its type name (case-insensitive, direct subclasses of
//! Action/Condition only), and each attribute is assigned by reflection to the
//! writable public property of the same name (OrdinalIgnoreCase). Attributes
//! without such a property are silently ignored. Values parse as Enum.Parse
//! (ignoreCase), bool.Parse, invariant int/float, comma-separated
//! Vector2/3/4/Color, or a lowercased string. A script action is therefore
//! fully described by a class name plus a property map, which is what
//! [`ScriptCall`] carries. Calls build the same [`XmlElement`] the scene
//! loader would, so behaviour is shared with authored triggers.
//!
//! [`native::ACTIONS`] and [`native::CONDITIONS`] are generated from the
//! decompilation (see `output/research/script-schema.md`).
use crate::scene_script::XmlElement;

// Generated by gen_schema.py (see its header); keep its one-line-per-entry form.
#[rustfmt::skip]
pub mod native;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Family {
    Action,
    Condition,
}

#[derive(Clone, Copy, Debug)]
pub enum EnumMembers {
    Names(&'static [&'static str]),
    /// Name/value pairs shared with another generated table.
    Indexed(&'static [(&'static str, i32)]),
}

#[derive(Debug)]
pub struct EnumSchema {
    pub name: &'static str,
    pub members: EnumMembers,
    /// `[Flags]`: Enum.Parse ORs comma-separated members.
    pub flags: bool,
}

impl EnumSchema {
    pub fn names(&self) -> Vec<&'static str> {
        match self.members {
            EnumMembers::Names(n) => n.to_vec(),
            EnumMembers::Indexed(p) => p.iter().map(|(n, _)| *n).collect(),
        }
    }
    /// Enum.Parse(type, value, ignoreCase: true): a member name, a decimal
    /// integer, or (any enum) a comma-separated list of either.
    pub fn accepts(&self, value: &str) -> bool {
        let names = self.names();
        value.split(',').all(|part| {
            let part = part.trim();
            !part.is_empty()
                && (part.parse::<i64>().is_ok()
                    || names.iter().any(|n| n.eq_ignore_ascii_case(part)))
        })
    }
}

#[derive(Clone, Copy, Debug)]
pub enum ValueKind {
    String,
    Float,
    Int,
    Bool,
    Vector2,
    Vector3,
    Vector4,
    Color,
    Enum(&'static EnumSchema),
}

#[derive(Debug)]
pub struct PropertySchema {
    pub name: &'static str,
    pub kind: ValueKind,
    /// Declared on the Action/Condition base (Delay, Invert).
    pub inherited: bool,
}

#[derive(Debug)]
pub struct ClassSchema {
    pub name: &'static str,
    pub family: Family,
    pub properties: &'static [PropertySchema],
}

impl ClassSchema {
    pub fn property(&self, name: &str) -> Option<&'static PropertySchema> {
        self.properties
            .iter()
            .find(|p| p.name.eq_ignore_ascii_case(name))
    }
}

/// Action.GetType: case-insensitive class lookup.
pub fn action_class(name: &str) -> Option<&'static ClassSchema> {
    native::ACTIONS
        .iter()
        .find(|c| c.name.eq_ignore_ascii_case(name))
}

pub fn condition_class(name: &str) -> Option<&'static ClassSchema> {
    native::CONDITIONS
        .iter()
        .find(|c| c.name.eq_ignore_ascii_case(name))
}

/// A typed argument from a host language, formatted into the attribute text
/// the native reflection reader parses.
#[derive(Clone, Debug, PartialEq)]
pub enum ScriptValue {
    Str(String),
    Float(f32),
    Int(i32),
    Bool(bool),
    Vector(Vec<f32>),
}

impl ScriptValue {
    pub fn to_attribute(&self) -> String {
        match self {
            Self::Str(s) => s.clone(),
            Self::Float(v) => format_float(*v),
            Self::Int(v) => v.to_string(),
            Self::Bool(v) => if *v { "true" } else { "false" }.into(),
            Self::Vector(v) => v
                .iter()
                .map(|x| format_float(*x))
                .collect::<Vec<_>>()
                .join(","),
        }
    }
}

impl From<&str> for ScriptValue {
    fn from(v: &str) -> Self {
        Self::Str(v.into())
    }
}
impl From<String> for ScriptValue {
    fn from(v: String) -> Self {
        Self::Str(v)
    }
}
impl From<f32> for ScriptValue {
    fn from(v: f32) -> Self {
        Self::Float(v)
    }
}
impl From<i32> for ScriptValue {
    fn from(v: i32) -> Self {
        Self::Int(v)
    }
}
impl From<bool> for ScriptValue {
    fn from(v: bool) -> Self {
        Self::Bool(v)
    }
}
impl From<[f32; 3]> for ScriptValue {
    fn from(v: [f32; 3]) -> Self {
        Self::Vector(v.to_vec())
    }
}

/// Round-trip float text (Rust's shortest representation parses back to the
/// same f32 under invariant float.Parse).
fn format_float(v: f32) -> String {
    format!("{v:?}")
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum CallError {
    UnknownClass(Family, String),
    /// The native reader throws FormatException/ArgumentException.
    InvalidValue {
        class: &'static str,
        property: &'static str,
        value: String,
    },
}

/// Whether native reflection parsing would accept `value` for `kind`.
pub fn accepts(kind: ValueKind, value: &str) -> bool {
    let floats = |n: usize| {
        let parts: Vec<_> = value.split(',').collect();
        // Native indexes the first n parts; extra parts are ignored.
        parts.len() >= n && parts[..n].iter().all(|p| p.trim().parse::<f32>().is_ok())
    };
    match kind {
        ValueKind::String => true,
        ValueKind::Float => value.trim().parse::<f32>().is_ok(),
        ValueKind::Int => value.trim().parse::<i32>().is_ok(),
        ValueKind::Bool => {
            let v = value.trim();
            v.eq_ignore_ascii_case("true") || v.eq_ignore_ascii_case("false")
        }
        ValueKind::Vector2 => floats(2),
        ValueKind::Vector3 => floats(3),
        ValueKind::Vector4 | ValueKind::Color => floats(4),
        ValueKind::Enum(e) => e.accepts(value),
    }
}

/// One action or condition invocation: class name plus property arguments.
/// Unknown properties are kept (native ignores them) so that readers which
/// consume constructor-level XML still see what the caller passed.
#[derive(Clone, Debug)]
pub struct ScriptCall {
    pub class: String,
    pub args: Vec<(String, ScriptValue)>,
    /// Child elements, for the few classes whose constructor reads XmlNode
    /// children (Spawn's equipment, SpawnCloneWizards, ...).
    pub children: Vec<XmlElement>,
}

impl ScriptCall {
    pub fn new(class: impl Into<String>) -> Self {
        Self {
            class: class.into(),
            args: Vec::new(),
            children: Vec::new(),
        }
    }
    pub fn arg(mut self, name: impl Into<String>, value: impl Into<ScriptValue>) -> Self {
        self.args.push((name.into(), value.into()));
        self
    }
    pub fn child(mut self, element: XmlElement) -> Self {
        self.children.push(element);
        self
    }

    /// Validate against the native class and build the element Action.Read
    /// or Condition.Read would see. The element name is the native class
    /// spelling.
    pub fn element(&self, family: Family) -> Result<XmlElement, CallError> {
        let class = match family {
            Family::Action => action_class(&self.class),
            Family::Condition => condition_class(&self.class),
        }
        .ok_or_else(|| CallError::UnknownClass(family, self.class.clone()))?;
        let mut attributes = Vec::with_capacity(self.args.len());
        for (name, value) in &self.args {
            let text = value.to_attribute();
            if let Some(p) = class.property(name) {
                if !accepts(p.kind, &text) {
                    return Err(CallError::InvalidValue {
                        class: class.name,
                        property: p.name,
                        value: text,
                    });
                }
            }
            attributes.push((name.clone(), text));
        }
        let mut element = XmlElement::synthetic(class.name, attributes);
        element.children = self.children.clone();
        Ok(element)
    }
}
