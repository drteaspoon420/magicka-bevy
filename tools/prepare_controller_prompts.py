#!/usr/bin/env python3
"""Copy the selected CC0 Kenney prompts and embed exact PNG bytes as Rust.

Run from any directory. The text-only publication guard intentionally keeps raw
PNGs local; embedded.rs makes the same graphics available in clean checkouts.
This tool never reads target/ and needs no additional Python packages.
"""
from pathlib import Path
import hashlib
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "extra_assets/kenney_input_prompts"
DESTINATION = ROOT / "output/rewrite/assets/input_prompts"
# South, East, West, North, LB, RB, LT, RT, Start, Select, Left stick, Right stick/pad, D-pad.
ASSETS = {
 'xbox':('Xbox Series',['xbox_button_a','xbox_button_b','xbox_button_x','xbox_button_y','xbox_lb','xbox_rb','xbox_lt','xbox_rt','xbox_button_menu','xbox_button_view','xbox_stick_l','xbox_stick_r','xbox_dpad','xbox_dpad_up','xbox_dpad_down','xbox_dpad_left','xbox_dpad_right']),
 'ps5':('PlayStation Series',['playstation_button_cross','playstation_button_circle','playstation_button_square','playstation_button_triangle','playstation_trigger_l1','playstation_trigger_r1','playstation_trigger_l2','playstation_trigger_r2','playstation5_button_options','playstation5_button_create','playstation_stick_l','playstation_stick_r','playstation_dpad','playstation_dpad_up','playstation_dpad_down','playstation_dpad_left','playstation_dpad_right']),
 'deck':('Steam Deck',['steamdeck_button_a','steamdeck_button_b','steamdeck_button_x','steamdeck_button_y','steamdeck_button_l1','steamdeck_button_r1','steamdeck_button_l2','steamdeck_button_r2','steamdeck_button_options','steamdeck_button_view','steamdeck_stick_l','steamdeck_stick_r','steamdeck_dpad','steamdeck_dpad_up','steamdeck_dpad_down','steamdeck_dpad_left','steamdeck_dpad_right']),
 'steam':('Steam Controller',['steam_button_a','steam_button_b','steam_button_x','steam_button_y','steam_lb','steam_rb','steam_lt','steam_rt','steam_button_start_icon','steam_button_back_icon','steam_stick','steam_pad','steam_dpad','steam_dpad_up','steam_dpad_down','steam_dpad_left','steam_dpad_right'])}

# Directional right-stick / right-trackpad art, in cardinal order Right Up Left Down.
for family, (_, names) in ASSETS.items():
    prefix = {'xbox':'xbox_stick_r','ps5':'playstation_stick_r','deck':'steamdeck_stick_r','steam':'steam_pad'}[family]
    names.extend(prefix+'_'+direction for direction in ('right','up','left','down'))
    names.extend(['@flair_arrow_short','@flair_plus'])

def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    body = [
        "// Kenney Input Prompts 1.5A (CC0). Exact PNG bytes, not extracted target assets.",
        "// Generated by tools/prepare_controller_prompts.py.",
        "pub const PNGS: [[&[u8]; 23]; 4] = [",
    ]
    for family, (folder, names) in ASSETS.items():
        destination = DESTINATION / family
        destination.mkdir(exist_ok=True)
        body.append("    [")
        for name in names:
            source = SOURCE / ("Flairs" if name.startswith("@") else folder) / "Default" / f"{name.lstrip(chr(64))}.png"
            data = source.read_bytes()
            shutil.copyfile(source, destination / source.name)
            body.append(f"        // {source.relative_to(SOURCE)} sha256: {hashlib.sha256(data).hexdigest()}")
            body.append("        &[")
            for offset in range(0, len(data), 24):
                body.append("            " + ",".join(str(byte) for byte in data[offset:offset + 24]) + ",")
            body.append("        ],")
        body.append("    ],")
    body.append("];")
    embedded = DESTINATION / "embedded.rs"
    embedded.write_text("\n".join(body) + "\n")
    (DESTINATION / "LICENSE.md").write_text("\n".join(line.rstrip() for line in (SOURCE / "License.txt").read_text().splitlines()) + "\n")
    subprocess.run(["rustfmt", "--edition", "2021", str(embedded)], check=True)
    print(f"Copied and embedded {sum(len(names) for _, names in ASSETS.values())} CC0 prompts.")


if __name__ == "__main__":
    main()
