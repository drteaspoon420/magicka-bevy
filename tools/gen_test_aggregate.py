#!/usr/bin/env python3
"""Regenerate a crate's aggregated integration-test entry point.

Cargo builds one executable per file in `tests/`. For crates whose tests link
a large dependency graph (magicka-runtime: Bevy/physics), that means one
multi-hundred-megabyte link per file, and a change to the library relinks
every executable that is requested. This script writes `tests/<name>.rs` that
declares every other `tests/*.rs` file as a module, so the crate's Cargo.toml
can set `autotests = false` and register that single `[[test]]`.

Nested `#[path = "support/..."]` modules keep resolving relative to `tests/`
because rustc treats a `#[path]`-loaded file as a directory owner.

Usage: tools/gen_test_aggregate.py crates/magicka-runtime [--name all] [--check]
"""
import argparse
import pathlib
import sys

HEADER = """//! Generated by tools/gen_test_aggregate.py; do not edit by hand.
//!
//! Every integration test of this crate is a module of this one executable,
//! so the dependency graph links once. Run one former suite with
//! `cargo test -p <crate> --test {name} <module>::` (for example
//! `--test {name} scene_flow::`). Rerun the generator after adding or
//! removing a file in `tests/`; `registered_modules_match_test_files` fails
//! until the list is current.
#![allow(clippy::all)]

"""

GUARD = """
#[test]
fn registered_modules_match_test_files() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests");
    let mut files: Vec<String> = std::fs::read_dir(&dir)
        .expect("tests directory")
        .filter_map(|e| e.ok())
        .filter(|e| e.path().extension().map_or(false, |x| x == "rs"))
        .map(|e| e.path().file_stem().unwrap().to_string_lossy().into_owned())
        .filter(|s| s != "__NAME__")
        .collect();
    files.sort();
    let registered: Vec<&str> = REGISTERED.to_vec();
    assert_eq!(
        files, registered,
        "tests/ changed: rerun tools/gen_test_aggregate.py __CRATE__"
    );
}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("crate", help="crate directory, e.g. crates/magicka-runtime")
    ap.add_argument("--name", default="all", help="aggregate test name")
    ap.add_argument("--check", action="store_true", help="exit 1 if stale")
    args = ap.parse_args()
    crate = pathlib.Path(args.crate)
    tests = crate / "tests"
    stems = sorted(
        p.stem for p in tests.glob("*.rs") if p.stem != args.name
    )
    body = HEADER.replace("{name}", args.name)
    for s in stems:
        body += f'#[path = "{s}.rs"]\nmod {s};\n'
    body += "\nconst REGISTERED: &[&str] = &[\n"
    for s in stems:
        body += f'    "{s}",\n'
    body += "];\n"
    body += GUARD.replace("__NAME__", args.name).replace("__CRATE__", crate.as_posix())
    out = tests / f"{args.name}.rs"
    current = out.read_text() if out.exists() else None
    if args.check:
        if current != body:
            print(f"{out} is stale; rerun without --check", file=sys.stderr)
            return 1
        return 0
    if current != body:
        out.write_text(body)
        print(f"wrote {out} ({len(stems)} modules)")
    else:
        print(f"{out} unchanged ({len(stems)} modules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
